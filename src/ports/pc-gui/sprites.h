/* ===== TEXT DRAWING HELPERS ===== */

static inline void lcd_draw_digit(int x, int y, int digit)
{
    if (digit >= 0 && digit <= 9) {
        lcd_draw_sprite(x, y, FONT_DIGITS[digit], DIGIT_W, DIGIT_H);
    }
}

static inline void lcd_draw_digit_inv(int x, int y, int digit)
{
    if (digit >= 0 && digit <= 9) {
        lcd_draw_sprite_inv(x, y, FONT_DIGITS[digit], DIGIT_W, DIGIT_H);
    }
}

/* Draw a number (right-aligned at x, or left-aligned) */
static inline void lcd_draw_number(int x, int y, uint32_t num)
{
    char buf[12];
    int len = 0;
    if (num == 0) {
        lcd_draw_digit(x, y, 0);
        return;
    }
    uint32_t tmp = num;
    while (tmp > 0) {
        buf[len++] = (char)(tmp % 10);
        tmp /= 10;
    }
    for (int i = len - 1; i >= 0; i--) {
        lcd_draw_digit(x, y, buf[i]);
        x += DIGIT_W + 1;
    }
}

/* Draw a text string using the small 5x7 font */
static inline void lcd_draw_text(int x, int y, const char *text)
{
    while (*text) {
        char c = *text;
        if (c >= SFONT_FIRST && c <= SFONT_LAST) {
            lcd_draw_sprite(x, y, FONT_SMALL[c - SFONT_FIRST], SFONT_W, SFONT_H);
        }
        x += SFONT_W + 1;
        text++;
    }
}

/* Draw text with inverted pixels (for selected menu items) */
static inline void lcd_draw_text_inv(int x, int y, const char *text)
{
    while (*text) {
        char c = *text;
        if (c >= SFONT_FIRST && c <= SFONT_LAST) {
            lcd_draw_sprite_inv(x, y, FONT_SMALL[c - SFONT_FIRST], SFONT_W, SFONT_H);
        }
        x += SFONT_W + 1;
        text++;
    }
}

/* Measure text width in LCD pixels */
static inline int lcd_text_width(const char *text)
{
    int w = 0;
    while (*text) {
        w += SFONT_W + 1;
        text++;
    }
    return w > 0 ? w - 1 : 0;  /* subtract trailing spacing */
}

